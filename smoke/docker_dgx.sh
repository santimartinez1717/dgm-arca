#!/usr/bin/env bash
# docker compose inside a DGX session, with the session's MIG partition visible.
#
#   smoke/docker_dgx.sh build
#   smoke/docker_dgx.sh run --rm check-gpu
#   smoke/docker_dgx.sh up api
#
# The DGX sessions have rootless Docker with the GPUs exposed through CDI, so the compose GPU
# reservation already mounts the node's GPUs (Slurm only lets us open ours). What it does not
# mount are the MIG capability files (/dev/nvidia-caps/nvidia-capN) that CUDA needs to open a
# MIG partition, and their numbers change with every session. This script finds the ones the
# session can open, writes a compose override that adds them, and passes everything else to
# docker compose. On any other machine use plain `docker compose`.
set -euo pipefail
cd "$(dirname "$0")/.."

caps=$(python3 - <<'EOF'
import glob, os
for path in sorted(glob.glob("/dev/nvidia-caps/nvidia-cap*")):
    try:
        os.close(os.open(path, os.O_RDONLY))
    except OSError:
        continue
    print(path)
EOF
)
if [ -z "$caps" ]; then
    echo "No MIG capability file can be opened: is this a DGX session with a GPU?" >&2
    exit 1
fi

override="${TMPDIR:-/tmp}/arca-compose-dgx-$(id -u).yml"
{
    echo "# Generated by smoke/docker_dgx.sh for this session; do not edit."
    echo "services:"
    for service in api check-gpu smoke train; do
        echo "  $service:"
        echo "    devices:"
        for cap in $caps; do echo "      - $cap"; done
    done
} > "$override"

# Models go to the cluster's shared cache, as with smoke/dgx_env.sh.
export HF_CACHE_DIR="${HF_CACHE_DIR:-$HOME/clusters/dgx/.hf_cache}"
exec docker compose -f docker-compose.yml -f "$override" "$@"
